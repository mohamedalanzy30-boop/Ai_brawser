// Neural path in the page: ONNX Runtime Web (wasm here, WebGPU on the phone) loads the model from the app's asset host,
// runs on live video frames, and the 4x output is what the overlay shows.
const { ENGINE, launch, run, check, canvasVideo, routeAssets, ortScript } = require('./lib')
run('nnpath: neural 4x on video frames', async () => {
  const browser = await launch()
  const page = await browser.newPage({ viewport: { width: 800, height: 500 } })
  await routeAssets(page)
  await page.route('https://test.local/', r => r.fulfill({ contentType: 'text/html', body: '<body style="margin:0"><video id=v style="width:640px;height:360px"></video>' }))
  await page.goto('https://test.local/')
  await page.evaluate(canvasVideo, { id: 'v', split: true })
  await page.waitForFunction(() => document.getElementById('v').videoWidth > 0)
  await page.addScriptTag({ content: ortScript() })
  await page.addScriptTag({ content: ENGINE })
  await page.evaluate(() => window.__minEnhanceSet({ enabled: true, neural: true, tone: false, target: 1080 }))
  await page.waitForFunction(() => { const n = window.__minEnhance.state.nn; return n && n.last }, null, { timeout: 30000 }).catch(() => {})
  const r = await page.evaluate(() => { const n = window.__minEnhance.state.nn; return { stats: window.__minEnhance.state.stats.nn, ms: n && Math.round(n.ms), out: n && n.last && [n.last.w, n.last.h, n.last.planes.constructor.name, n.last.planes.length] } })
  check('model loaded from the asset host', /^ready:/.test(r.stats), r.stats)
  check('a frame went through the model: 640x360 float output', !!r.out && r.out[0] === 640 && r.out[1] === 360 && r.out[2] === 'Float32Array' && r.out[3] === 3 * 640 * 360, r.out)
  await browser.close()
})
