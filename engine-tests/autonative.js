// A long video (>= 10 min) that starts playing is handed to the native player once; a short one is not.
const { ENGINE, fixture, serveMedia, check, run } = require('./lib')
run(async (browser) => {
  const page = await browser.newPage()
  await page.route('https://test.local/', r => r.fulfill({ contentType: 'text/html', body: '<body><video id=s muted src="/short.webm" style="width:400px;height:225px"></video><video id=l muted src="/long.webm" style="width:400px;height:225px"></video></body>' }))
  await page.route('https://test.local/short.webm', r => serveMedia(r, fixture('short.webm')))
  await page.route('https://test.local/long.webm', r => serveMedia(r, fixture('long.webm')))
  await page.addInitScript(() => { window.__calls = []; window.AIBNative = { playing () {}, autoNative: (s, t) => { window.__calls.push(s.split('/').pop()); return true }, openNative () {} } })
  await page.goto('https://test.local/')
  await page.addScriptTag({ content: ENGINE })
  await page.waitForFunction(() => document.getElementById('l').readyState >= 1 && document.getElementById('s').readyState >= 1)
  check(await page.evaluate(() => document.getElementById('l').duration >= 600 && document.getElementById('s').duration < 600), 'fixtures: long video >= 10 min, short video < 10 min')
  await page.evaluate(async () => { await document.getElementById('s').play(); await document.getElementById('l').play() })
  await page.waitForTimeout(500)
  check(await page.evaluate(() => document.getElementById('l').paused && !document.getElementById('s').paused), 'the handed-over long video is paused in the page, the short one plays')
  await page.evaluate(async () => { await document.getElementById('l').play() }) // second play: must not hand over again
  await page.waitForTimeout(300)
  const calls = await page.evaluate(() => window.__calls); const paused = await page.evaluate(() => document.getElementById('l').paused)
  console.log('  handed to native:', JSON.stringify(calls), ' long video paused:', paused)
  check(JSON.stringify(calls) === '["long.webm"]', 'only the long video is handed to the native player, once')
  check(paused === false, 'playing it again in the page is allowed (no second hand-over)')
}, ['--autoplay-policy=no-user-gesture-required'])
