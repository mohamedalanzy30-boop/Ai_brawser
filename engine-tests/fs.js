const { chromium } = require('playwright'); const fs = require('fs'); const path = require('path')
const ENGINE = path.resolve(__dirname, '../android/app/src/main/assets/engine.js')
;(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] })
  const page = await browser.newPage({ viewport: { width: 800, height: 500 } })
  page.on('pageerror', e => console.log('[pageerror]', e.message))
  await page.route('https://test.local/', r => r.fulfill({ contentType: 'text/html', body: '<body style="margin:0"><div id=box style="width:640px;height:360px"><video id=v muted autoplay style="width:640px;height:360px"></video></div></body>' }))
  await page.goto('https://test.local/')
  await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 160; c.height = 90; const x = c.getContext('2d'); setInterval(() => { x.fillStyle = '#345'; x.fillRect(0, 0, 160, 90) }, 33); const v = document.getElementById('v'); v.srcObject = c.captureStream(30); v.play() })
  await page.waitForFunction(() => document.getElementById('v').videoWidth > 0)
  await page.addScriptTag({ content: fs.readFileSync(ENGINE, 'utf8') })
  await page.evaluate(() => window.__minEnhanceSet({ enabled: true, neural: false }))
  await page.mouse.move(300, 200); await page.mouse.click(300, 200); await page.waitForTimeout(900)
  const info = () => page.evaluate(() => { const b = document.querySelector('[data-aib-fs]'); return b ? { display: b.style.display, text: b.textContent, left: b.style.left, top: b.style.top, fs: document.fullscreenElement && document.fullscreenElement.id } : null })
  console.log('after touch', JSON.stringify(await info()))
  await page.click('[data-aib-fs]'); await page.waitForTimeout(800)
  console.log('after click', JSON.stringify(await info()))
  await page.screenshot({ path: path.join(__dirname, 'fs.png') })
  await browser.close()
})()
