// Fullscreen button: appears on touch over the video, puts the player box (not only the <video>) in fullscreen, then shows ✕.
const { ENGINE, launch, run, check, canvasVideo } = require('./lib')
run('fs: fullscreen button', async () => {
  const browser = await launch()
  const page = await browser.newPage({ viewport: { width: 800, height: 500 } })
  page.on('pageerror', e => console.log('   [pageerror]', e.message))
  await page.route('https://test.local/', r => r.fulfill({ contentType: 'text/html', body: '<body style="margin:0"><div id=box style="width:640px;height:360px"><video id=v style="width:640px;height:360px"></video></div></body>' }))
  await page.addInitScript(() => { window.__minCfg0 = { gestures: true } })
  await page.goto('https://test.local/')
  await page.evaluate(canvasVideo, 'v')
  await page.waitForFunction(() => document.getElementById('v').videoWidth > 0)
  await page.addScriptTag({ content: ENGINE })
  await page.evaluate(() => window.__minEnhanceSet({ enabled: true, neural: false }))
  await page.mouse.move(300, 200); await page.mouse.click(300, 200); await page.waitForTimeout(900)
  const info = () => page.evaluate(() => { const b = document.querySelector('[data-aib-fs]'); return b ? { display: b.style.display, text: b.textContent, fs: document.fullscreenElement && document.fullscreenElement.id } : null })
  const a = await info()
  check('button shown after a touch', a && a.display === 'block' && a.text === '⛶', a)
  await page.click('[data-aib-fs]'); await page.waitForTimeout(800)
  const b = await info()
  check('fullscreen on the player box, button turns into ✕', b && b.fs === 'box' && b.text === '✕', b)
  const overlayHost = await page.evaluate(() => { const c = document.querySelector('canvas[style*="fixed"]'); return c && c.parentElement && c.parentElement.id })
  check('the enhancement overlay moved into the fullscreen box', overlayHost === 'box', overlayHost)
  await browser.close()
})
